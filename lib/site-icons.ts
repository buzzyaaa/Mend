const EXACT = new Map<string, SiteIcon>()
for (const icon of SITE_ICONS) {
  for (const domain of icon.domains) EXACT.set(domain, icon)
}

/**
 * Find the brand icon for a plaintext website string. Accepts a full URL, a
 * bare hostname, or an empty value; unknown sites return null so the caller
 * can fall back to the category icon.
 */
export function siteIconForUrl(url: string | null | undefined): SiteIcon | null {
  const raw = typeof url === 'string' ? url.trim() : ''
  if (!raw) return null

  let host: string
  try {
    const withScheme = /^[a-z][a-z0-9+.-]*:\/\//i.test(raw) ? raw : `https://${raw}`
    host = new URL(withScheme).hostname.toLowerCase()
  } catch {
    return null
  }
  if (host.startsWith('www.')) host = host.slice(4)

  const exact = EXACT.get(host)
  if (exact) return exact

  // Walk parent domains so mail.google.com -> gmail.com (exact above) and
  // foo.github.io -> github.com, while unrelated domains stay unmatched.
  for (let dot = host.indexOf('.'); dot !== -1; dot = host.indexOf('.', dot + 1)) {
    const parent = host.slice(dot + 1)
    const hit = EXACT.get(parent)
    if (hit) return hit
  }
  return null
}
